import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
export function sourceFingerprint() {
  const names = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], { encoding: 'utf8' }).split('\0').filter(Boolean);
  const hash = createHash('sha256');
  for (const name of [...new Set(names)].sort()) {
    if (name === 'next-env.d.ts') continue; // Generated by Next for the selected output directory.
    hash.update(name); hash.update('\0');
    hash.update(existsSync(name) && statSync(name).isFile() ? readFileSync(name) : '<deleted>'); hash.update('\0');
  }
  return hash.digest('hex');
}
export const requiredGates = ['install', 'generate', 'unit', 'integration', 'build', 'http', 'secrets', 'history', 'diff', 'image', 'preview', 'audit'];
export function assertDeployable(manifest, sourceHash, imageId) {
  if (manifest.schema !== 1 || manifest.approved !== true || requiredGates.some(name => manifest.gates?.[name] !== 'passed')) throw new Error('Release has not passed all required checks');
  if (manifest.sourceHash !== sourceHash) throw new Error('Source changed after acceptance; prepare a new release');
  if (!/^sha256:[a-f0-9]{64}$/.test(imageId) || manifest.imageId !== imageId) throw new Error('Candidate image changed after acceptance');
}
export function releaseName(value) {
  if (!value || !/^[a-z0-9][a-z0-9-]{0,95}$/.test(value)) throw new Error('Invalid release/deployment ID');
  return value;
}
